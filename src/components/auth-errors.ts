/**
 * รหัส error → ข้อความไทย (null = ไม่มีรหัส = ไม่ต้องแสดงอะไร)
 * รหัสที่ไม่รู้จักได้ข้อความทั่วไป — ไม่ echo รหัสนั้นลงหน้าเว็บ
 */
export function authErrorFor(code: unknown): string | null {
  if (typeof code !== 'string' || code.trim() === '') return null;
  return MESSAGES[code] ?? GENERIC;
}

